#!/usr/bin/env node
/*
 * Adds Minecraft Java 26.3 (protocol 777) support to the installed Prismarine stack.
 * Runs automatically after `npm install` (postinstall) and is idempotent.
 *
 * 26.3 is NOT wire-compatible with 26.1: packet ids shifted (new post_effects, add_transient_block,
 * swing_animation and punch packets), several packets changed shape (login_finished, login,
 * teleport_confirm, entity movement, particles, teams, advancements, ...) and the block/item/
 * particle/component/attribute registries grew, shifting ids. Everything here was derived from the
 * vanilla 26.1.2 and 26.3 client jars, see scripts/mc-26.3/:
 *  - data/                 minecraft-data files for pc/26.3 (generated by tools/ from the game itself;
 *                          protocol.json is built from 26.1's by build-protocol.cjs)
 *  - datatypes.js          new minecraft-protocol datatypes (26.3 entity move deltas, byte-array BitSets)
 * plus small mineflayer changes for packets whose fields changed.
 *
 * Also still needed: mineflayer master's tick_end fix (package.json pins it).
 * Delete this script and the overrides once mineflayer and minecraft-data releases support 26.3.
 */
'use strict'
const fs = require('fs')
const path = require('path')
const { execFileSync } = require('child_process')

const NEW = '26.3'
const BASE = '26.1'
const PROTOCOL = 777
const here = path.join(__dirname, 'mc-26.3')
const root = path.resolve(__dirname, '..', 'node_modules')

function findPackages (name, dir = root, found = []) {
  if (!fs.existsSync(dir)) return found
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue
    const full = path.join(dir, entry.name)
    if (entry.name === name && fs.existsSync(path.join(full, 'package.json'))) found.push(full)
    if (entry.name.startsWith('@')) findPackages(name, full, found)
    const nested = path.join(full, 'node_modules')
    if (fs.existsSync(nested)) findPackages(name, nested, found)
  }
  return found
}

const readJson = f => JSON.parse(fs.readFileSync(f, 'utf8'))
const writeJson = (f, d) => fs.writeFileSync(f, JSON.stringify(d, null, 2) + '\n')
const rel = p => path.relative(root, p)
let changed = 0

/** Apply literal replacements to a file once; marker identifies an already-patched file. */
function patchFile (file, marker, edits) {
  let src = fs.readFileSync(file, 'utf8')
  if (src.includes(marker)) return false
  for (const [from, to, all] of edits) {
    if (!src.includes(from)) throw new Error(`[mc-26.3] ${rel(file)}: expected code not found, the patch needs updating:\n${from}`)
    src = all ? src.split(from).join(to) : src.replace(from, to)
  }
  fs.writeFileSync(file, src)
  return true
}

function addToVersionList (file, after) {
  if (!fs.existsSync(file)) return false
  const src = fs.readFileSync(file, 'utf8')
  if (src.includes(`'${NEW}'`)) return false
  const out = src.replace(`'${after}']`, `'${after}', '${NEW}']`)
  if (out === src) throw new Error(`Could not find '${after}'] in ${file}; the patch needs updating`)
  fs.writeFileSync(file, out)
  return true
}

// ---------------------------------------------------------------- minecraft-data
const shipped = fs.readdirSync(path.join(here, 'data')).filter(f => f.endsWith('.json'))
for (const pkg of findPackages('minecraft-data')) {
  const data = path.join(pkg, 'minecraft-data', 'data')
  const dataPathsFile = path.join(data, 'dataPaths.json')
  if (!fs.existsSync(dataPathsFile)) continue
  const dataPaths = readJson(dataPathsFile)
  if (!dataPaths.pc[BASE]) throw new Error(`${pkg} has no ${BASE} data; install minecraft-data >= 3.114`)

  const verDir = path.join(data, 'pc', NEW)
  fs.mkdirSync(verDir, { recursive: true })
  let touched = false
  for (const f of shipped) {
    const src = fs.readFileSync(path.join(here, 'data', f))
    const dst = path.join(verDir, f)
    if (!fs.existsSync(dst) || !fs.readFileSync(dst).equals(src)) { fs.writeFileSync(dst, src); touched = true }
  }
  const wanted = { ...dataPaths.pc[BASE] }
  for (const f of shipped) wanted[f.slice(0, -5)] = `pc/${NEW}`
  if (JSON.stringify(dataPaths.pc[NEW]) !== JSON.stringify(wanted)) { dataPaths.pc[NEW] = wanted; writeJson(dataPathsFile, dataPaths); touched = true }

  const versionsFile = path.join(data, 'pc', 'common', 'versions.json')
  const versions = readJson(versionsFile)
  if (!versions.includes(NEW)) { versions.splice(versions.indexOf(BASE) + 1, 0, NEW); writeJson(versionsFile, versions); touched = true }

  const pvFile = path.join(data, 'pc', 'common', 'protocolVersions.json')
  const pv = readJson(pvFile)
  if (!pv.some(v => v.minecraftVersion === NEW)) {
    const baseEntry = pv.find(v => v.minecraftVersion === BASE)
    pv.splice(pv.indexOf(baseEntry), 0, { ...baseEntry, minecraftVersion: NEW, majorVersion: NEW, version: PROTOCOL, dataVersion: 5023 })
    writeJson(pvFile, pv)
    touched = true
  }

  if (touched) {
    execFileSync(process.execPath, [path.join(pkg, 'bin', 'generate_data.js')], { stdio: 'inherit' })
    console.log(`[mc-26.3] minecraft-data: installed ${NEW} data (${shipped.length} files) -> ${rel(pkg)}`)
    changed++
  }
}

// ---------------------------------------------------------------- minecraft-protocol
const MARK = '/* mc-26.3 */'
for (const pkg of findPackages('minecraft-protocol')) {
  if (addToVersionList(path.join(pkg, 'src', 'version.js'), BASE)) {
    console.log(`[mc-26.3] minecraft-protocol: added ${NEW} to supportedVersions -> ${rel(pkg)}`)
    changed++
  }
  // 26.3 datatypes (entityMoveDelta, bitSetLongs) for both the interpreter and the compiler
  const dt = path.join(pkg, 'src', 'datatypes')
  const typeSrc = fs.readFileSync(path.join(here, 'datatypes.js'))
  const typeDst = path.join(dt, 'mc-26.3-datatypes.js')
  if (!fs.existsSync(typeDst) || !fs.readFileSync(typeDst).equals(typeSrc)) { fs.writeFileSync(typeDst, typeSrc); changed++ }
  const appendOnce = (file, code) => {
    const src = fs.readFileSync(file, 'utf8')
    if (src.includes(MARK)) return false
    fs.writeFileSync(file, src.replace(/\s*$/, '\n') + code + '\n')
    return true
  }
  const p1 = appendOnce(path.join(dt, 'minecraft.js'), `Object.assign(module.exports, require('./mc-26.3-datatypes')) ${MARK}`)
  const p2 = appendOnce(path.join(dt, 'compiler-minecraft.js'),
    `for (const [n, [r, w, s]] of Object.entries(require('./mc-26.3-datatypes'))) { ${MARK}\n` +
    "  module.exports.Read[n] = ['native', r]; module.exports.Write[n] = ['native', w]; module.exports.SizeOf[n] = ['native', s]\n}")
  if (p1 || p2) { console.log(`[mc-26.3] minecraft-protocol: added 26.3 datatypes -> ${rel(pkg)}`); changed++ }
  // lpVec3's continued scale is an unsigned var-int (vanilla masks it with 0xffffffff); see
  // PrismarineJS/node-minecraft-protocol#1542. Read as signed, large velocities flipped sign.
  if (patchFile(path.join(dt, 'lpVec3.js'), 'varIntVal >>> 0', [
    ['    scale = (varIntVal * 4) + scale', '    scale = ((varIntVal >>> 0) * 4) + scale']
  ])) { console.log(`[mc-26.3] minecraft-protocol: lpVec3 unsigned scale -> ${rel(pkg)}`); changed++ }
}

// ---------------------------------------------------------------- mineflayer
for (const pkg of findPackages('mineflayer')) {
  if (addToVersionList(path.join(pkg, 'lib', 'version.js'), BASE)) {
    console.log(`[mc-26.3] mineflayer: added ${NEW} to testedVersions -> ${rel(pkg)}`)
    changed++
  }
  const plugins = path.join(pkg, 'lib', 'plugins')
  const physics = fs.readFileSync(path.join(plugins, 'physics.js'), 'utf8')
  if (!physics.includes("'tick_end'")) {
    console.warn(`[mc-26.3] WARNING: ${rel(pkg)} never sends tick_end; 26.3 servers will kick it. Use mineflayer master or > 4.39.0.`)
  }
  // teleport_confirm now echoes the resulting position and rotation (extra fields are ignored by older versions)
  const a = patchFile(path.join(plugins, 'physics.js'), MARK, [
    ["      bot._client.write('teleport_confirm', { teleportId })",
      `      ${MARK} bot._client.write('teleport_confirm', { teleportId, x: pos.x, y: pos.y, z: pos.z, yaw, pitch })`]
  ])
  // 26.3 servers kick ("Invalid move player packet") when a second position-carrying move packet
  // arrives before tick_end. After a teleport mineflayer sent position_look and then, in the same
  // tick, a 'position' refresh; vanilla sends at most one per tick, so do the same.
  const a2 = patchFile(path.join(plugins, 'physics.js'), 'sentPositionThisTick', [
    ['  let shouldUsePhysics = false\n', '  let shouldUsePhysics = false\n  let sentPositionThisTick = false // mc-26.3: at most one position packet per tick\n'],
    ["    if (sendsTickEnd) bot._client.write('tick_end', {})\n", "    if (sendsTickEnd) bot._client.write('tick_end', {})\n    sentPositionThisTick = false\n"],
    ["    bot._client.write('position', lastSent)", "    sentPositionThisTick = true\n    bot._client.write('position', lastSent)"],
    ["    bot._client.write('position_look', lastSent)", "    sentPositionThisTick = true\n    bot._client.write('position_look', lastSent)"],
    ['    if (!Number.isFinite(bot.entity.position.x)) return\n\n', '    if (!Number.isFinite(bot.entity.position.x)) return\n    if (sentPositionThisTick) return // a teleport reply already moved us this tick\n\n']
  ])
  const b = patchFile(path.join(plugins, 'entities.js'), MARK, [
    // move deltas moved into a 'delta' object (single delta or a stepped path, see entityMoveDelta.js)
    ['packet.dX / (128 * 32), packet.dY / (128 * 32), packet.dZ / (128 * 32)',
      '(packet.delta || packet).dX / (128 * 32), (packet.delta || packet).dY / (128 * 32), (packet.delta || packet).dZ / (128 * 32)', true],
    // sync_entity_position now carries a PositionPath and no velocity
    ['    entity.position.set(packet.x, packet.y, packet.z)\n    entity.velocity.set(packet.dx, packet.dy, packet.dz)\n',
      `    if (packet.path) { ${MARK}\n      const p = packet.path.type === 'stepped' ? (packet.path.data[packet.path.data.length - 1] || {}).position : packet.path.data\n      if (p) entity.position.set(p.x, p.y, p.z)\n    } else {\n      entity.position.set(packet.x, packet.y, packet.z)\n      entity.velocity.set(packet.dx, packet.dy, packet.dz)\n    }\n`],
    // the serverbound swing packet was replaced by 'punch' (always the main hand)
    ["    bot._client.write('arm_animation', packet)",
      "    if (bot._client.version && bot.registry.version['>=']('26.3')) {\n      if (hand === 0) bot._client.write('punch', {})\n    } else bot._client.write('arm_animation', packet)"],
    // other entities' swings now arrive as swing_animation instead of animation 0/3
    ["  bot._client.on('animation', (packet) => {",
      "  bot._client.on('swing_animation', (packet) => {\n    bot.emit('entitySwingArm', fetchEntity(packet.entityId))\n  })\n\n  bot._client.on('animation', (packet) => {"]
  ])
  // Second round, cross-checked against the 26.3 jar after comparing with the upstream 26.3 PRs
  // (PrismarineJS/mineflayer#4146, #4206):
  const is263 = "bot.registry.version['>=']('26.3')"
  // ServerboundPlayerActionPacket$Action gained CHANGE_DESTROY_DIRECTION at id 1: abort 1->2, stop 2->3, release use 5->6
  const c1 = patchFile(path.join(plugins, 'digging.js'), 'mc-26.3 player actions', [
    ['status: 2, // finish digging', `status: ${is263} ? 3 : 2, // finish digging (mc-26.3 player actions)`],
    ['status: 1, // cancel digging', `status: ${is263} ? 2 : 1, // cancel digging`]
  ])
  const c2 = patchFile(path.join(plugins, 'inventory.js'), 'mc-26.3 player actions', [
    ['      status: 5,\n', `      status: ${is263} ? 6 : 5, // release use item (mc-26.3 player actions)\n`]
  ])
  // Only the newest of several unanswered teleports is confirmed: a stale confirm (with its old position)
  // followed by the new one puts two position packets in one tick, which 26.3 kicks for.
  const c3 = patchFile(path.join(plugins, 'physics.js'), 'mc-26.3 newest teleport', [
    ['    reply.teleport = true\n',
      `    reply.teleport = true\n    if (${is263}) { // mc-26.3 newest teleport\n      for (let i = pendingReplies.length - 1; i >= 0; i--) if (pendingReplies[i].teleport) pendingReplies.splice(i, 1)\n    }\n`]
  ])
  // 26.3 servers no longer send entity_status 2 when a player leaves a bed; the pose leaving SLEEPING is the signal
  const c4 = patchFile(path.join(plugins, 'entities.js'), 'mc-26.3 wake', [
    ['      if (metas.sleeping_pos || metas.pose === 2) {\n        bot.emit(\'entitySleep\', entity)\n      }\n',
      `      if (metas.sleeping_pos || metas.pose === 2) {\n        bot.emit('entitySleep', entity)\n      }\n      if (metas.pose !== undefined && ${is263}) { // mc-26.3 wake\n        if (metas.pose === 2) entity._asleep263 = true\n        else if (entity._asleep263) { entity._asleep263 = false; bot.emit('entityWake', entity) }\n      }\n`]
  ])
  if (a || a2 || b || c1 || c2 || c3 || c4) { console.log(`[mc-26.3] mineflayer: adapted plugins to the 26.3 packets -> ${rel(pkg)}`); changed++ }
}

// ---------------------------------------------------------------- prismarine-chunk / prismarine-physics
// prismarine-chunk maps chunk formats by major version; 26.3 uses the 26.1 format
// (its global palette width is derived from the 26.3 block data: 16 bits).
for (const pkg of findPackages('prismarine-chunk')) {
  const file = path.join(pkg, 'src', 'index.js')
  const src = fs.readFileSync(file, 'utf8')
  if (src.includes(`'${NEW}':`)) continue
  const line = `    ${BASE}: require('./pc/1.18/chunk')`
  if (!src.includes(line)) throw new Error(`Unexpected prismarine-chunk layout in ${file}; the patch needs updating`)
  fs.writeFileSync(file, src.replace(line, `${line},\n    '${NEW}': require('./pc/1.18/chunk')`))
  console.log(`[mc-26.3] prismarine-chunk: mapped ${NEW} -> ${rel(pkg)}`)
  changed++
}

// prismarine-physics lists feature versions explicitly; extend every feature that covers 26.1.
for (const pkg of findPackages('prismarine-physics')) {
  const file = path.join(pkg, 'lib', 'features.json')
  if (!fs.existsSync(file)) continue
  const features = readJson(file)
  let touched = false
  for (const f of features) {
    if (f.versions.includes(BASE) && !f.versions.includes(NEW)) { f.versions.push(NEW); touched = true }
  }
  if (touched) {
    writeJson(file, features)
    console.log(`[mc-26.3] prismarine-physics: extended 26.1 features to ${NEW} -> ${rel(pkg)}`)
    changed++
  }
}

console.log(changed ? `[mc-26.3] done (${changed} change(s))` : '[mc-26.3] already patched')
